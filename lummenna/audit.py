"""Audit logging helpers for the Lummenna memory palace.

The audit log is tamper-evident: every row commits to the hash of the row before
it (a hash chain). ``log_audit_event`` computes and stores ``prev_hash`` and
``entry_hash`` for each row; ``verify_audit_chain`` recomputes the chain and
reports the first break (a deleted, reordered, or altered row). The columns are
added by migration 0005.

Hashing is a plain SHA-256 over a canonical, order-fixed serialisation of the
row's content fields plus the previous row's hash. It is *integrity* (detects
tampering by anyone who cannot also recompute the whole downstream chain), not a
secret-keyed MAC; a keyed/HMAC variant bound to a Pro key vault is future work
(see ROADMAP.md).
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
from dataclasses import dataclass

#: Fixed sentinel used as ``prev_hash`` for the very first (genesis) audit row.
#: Any constant works; this documents intent and makes a fresh chain deterministic.
GENESIS_PREV_HASH = "0" * 64


def compute_entry_hash(
    *,
    prev_hash: str,
    event_type: str | None,
    actor: str | None,
    resource_type: str | None,
    resource_id: int | None,
    action: str | None,
    metadata_json: str | None,
    client_ip: str | None,
    request_id: str | None,
    created_at: int | None,
) -> str:
    """Return the SHA-256 hash chaining this row to ``prev_hash``.

    The payload is a canonical JSON array with a fixed field order and
    ``ensure_ascii`` + sorted separators, so the same logical row always hashes
    identically across platforms and Python runs. ``created_at`` is included so
    the recorded time is covered by the integrity guarantee.
    """
    payload = json.dumps(
        [
            prev_hash,
            event_type,
            actor,
            resource_type,
            resource_id,
            action,
            metadata_json,
            client_ip,
            request_id,
            created_at,
        ],
        ensure_ascii=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _last_entry_hash(conn: sqlite3.Connection) -> str:
    """Return the most recent row's ``entry_hash``, or the genesis sentinel."""
    try:
        row = conn.execute(
            "SELECT entry_hash FROM audit_log "
            "WHERE entry_hash IS NOT NULL ORDER BY audit_id DESC LIMIT 1"
        ).fetchone()
    except sqlite3.OperationalError:
        # Schema predates migration 0005 (no entry_hash column). Callers on such
        # schemas get a plain insert with no chaining (handled in log_audit_event).
        return GENESIS_PREV_HASH
    return row[0] if row and row[0] else GENESIS_PREV_HASH


def _has_chain_columns(conn: sqlite3.Connection) -> bool:
    cols = {row[1] for row in conn.execute("PRAGMA table_info(audit_log)").fetchall()}
    return "entry_hash" in cols and "prev_hash" in cols


def log_audit_event(
    conn: sqlite3.Connection,
    event_type: str,
    actor: str | None,
    resource_type: str | None,
    resource_id: int | None,
    action: str | None,
    metadata_json: str | None,
    client_ip: str | None,
    request_id: str | None,
    *,
    commit: bool = True,
) -> None:
    """Append a tamper-evident row to ``audit_log``.

    The row is linked into the hash chain (``prev_hash`` -> ``entry_hash``) when
    the schema has the chain columns (migration 0005); on older schemas it falls
    back to a plain insert.

    ``commit`` controls whether this call commits. Pass ``commit=False`` to make
    the audit write share the caller's transaction — e.g. right-to-be-forgotten
    must record the erasure and perform it atomically, so a failure cannot leave
    a committed "erased" claim while the data survives.
    """
    # created_at is generated by the table DEFAULT; to include it in the hash we
    # must know its value at insert time, so compute it here explicitly and pass
    # it in (the DEFAULT is unixepoch()). This keeps the stored value and the
    # hashed value identical.
    created_at = int(conn.execute("SELECT unixepoch()").fetchone()[0])

    if _has_chain_columns(conn):
        prev_hash = _last_entry_hash(conn)
        entry_hash = compute_entry_hash(
            prev_hash=prev_hash,
            event_type=event_type,
            actor=actor,
            resource_type=resource_type,
            resource_id=resource_id,
            action=action,
            metadata_json=metadata_json,
            client_ip=client_ip,
            request_id=request_id,
            created_at=created_at,
        )
        conn.execute(
            """
            INSERT INTO audit_log (
                event_type, actor, resource_type, resource_id,
                action, metadata_json, client_ip, request_id,
                created_at, prev_hash, entry_hash
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                event_type,
                actor,
                resource_type,
                resource_id,
                action,
                metadata_json,
                client_ip,
                request_id,
                created_at,
                prev_hash,
                entry_hash,
            ),
        )
    else:
        conn.execute(
            """
            INSERT INTO audit_log (
                event_type, actor, resource_type, resource_id,
                action, metadata_json, client_ip, request_id, created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                event_type,
                actor,
                resource_type,
                resource_id,
                action,
                metadata_json,
                client_ip,
                request_id,
                created_at,
            ),
        )
    if commit:
        conn.commit()


@dataclass(frozen=True)
class AuditChainResult:
    """Outcome of verifying the audit hash chain."""

    ok: bool
    rows_checked: int
    #: audit_id at which the chain first broke, or None when intact.
    broken_at: int | None = None
    reason: str | None = None


def verify_audit_chain(conn: sqlite3.Connection) -> AuditChainResult:
    """Recompute the audit hash chain and report the first break.

    Walks rows in ``audit_id`` (append) order, recomputing each ``entry_hash``
    from the stored fields and the running ``prev_hash``. A break means a row was
    deleted, reordered, or had a hashed field altered after the fact.

    Returns an :class:`AuditChainResult`. On a schema without the chain columns,
    returns ``ok=False`` with an explanatory reason (integrity is unavailable
    until migration 0005 has run).
    """
    if not _has_chain_columns(conn):
        return AuditChainResult(
            ok=False,
            rows_checked=0,
            reason="audit_log has no hash-chain columns; run migration 0005",
        )

    rows = conn.execute(
        """SELECT audit_id, event_type, actor, resource_type, resource_id,
                  action, metadata_json, client_ip, request_id, created_at,
                  prev_hash, entry_hash
           FROM audit_log
           ORDER BY audit_id ASC"""
    ).fetchall()

    expected_prev = GENESIS_PREV_HASH
    checked = 0
    for row in rows:
        (
            audit_id,
            event_type,
            actor,
            resource_type,
            resource_id,
            action,
            metadata_json,
            client_ip,
            request_id,
            created_at,
            stored_prev,
            stored_entry,
        ) = row
        checked += 1

        if stored_prev != expected_prev:
            return AuditChainResult(
                ok=False,
                rows_checked=checked,
                broken_at=audit_id,
                reason="prev_hash does not match preceding row (row deleted or reordered)",
            )

        recomputed = compute_entry_hash(
            prev_hash=stored_prev,
            event_type=event_type,
            actor=actor,
            resource_type=resource_type,
            resource_id=resource_id,
            action=action,
            metadata_json=metadata_json,
            client_ip=client_ip,
            request_id=request_id,
            created_at=created_at,
        )
        if recomputed != stored_entry:
            return AuditChainResult(
                ok=False,
                rows_checked=checked,
                broken_at=audit_id,
                reason="entry_hash mismatch (row content altered)",
            )
        expected_prev = stored_entry

    return AuditChainResult(ok=True, rows_checked=checked)


def audit_from_request(
    conn: sqlite3.Connection,
    event_type: str,
    action: str,
    resource_id: int | None,
    request,
    metadata_dict: dict | None = None,
) -> None:
    """Convenience wrapper that extracts client_ip / request_id from a request
    object (e.g. FastAPI Request) and forwards the audit event.
    """
    client_ip = None
    request_id = None
    if hasattr(request, "client") and request.client:
        client_ip = request.client.host
    if hasattr(request, "headers"):
        request_id = request.headers.get("x-request-id")
    metadata_json = json.dumps(metadata_dict) if metadata_dict else None
    log_audit_event(
        conn=conn,
        event_type=event_type,
        actor=None,
        resource_type=None,
        resource_id=resource_id,
        action=action,
        metadata_json=metadata_json,
        client_ip=client_ip,
        request_id=request_id,
    )
